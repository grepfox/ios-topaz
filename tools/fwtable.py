#!/usr/bin/env python3
"""
Firmware tables for TopazModem from a NON-HLOS.bin (the FAT16 volume of the phone's modem
partition): where each file lies, so the kernel reads it straight from the partition
(sweet_ufs_read_part) without a filesystem driver.

  tools/fwtable.py NON-HLOS.bin > tables.h

Prints three C tables of the types iokit/Kernel/arm/TopazModem.cpp declares:
  fw_files_vayu[]  struct fw_file { "modem.bNN", off, size, crc32 }   image/modem.* (must be one extent each)
  fw_ext_vayu[]    struct fw_extent { off, len }                         every file's extents, in order
  fw_all_vayu[]    struct fw_entry { "image/...", size, ext, next }     every file (lowercase long names)
Offsets are bytes from the start of the partition. Only file names, offsets, sizes and CRCs
are printed, none of the firmware.
"""
import struct
import sys
import zlib


def main(path):
    f = open(path, 'rb')
    bs = f.read(512)
    bps, spc, rsv, nfat, nroot, tot16, _, spf = struct.unpack_from('<HBHBHHBH', bs, 11)
    tot32 = struct.unpack_from('<I', bs, 32)[0]
    total = tot16 or tot32
    csize = bps * spc
    fat_off = rsv * bps
    root_off = fat_off + nfat * spf * bps
    data_off = root_off + ((nroot * 32 + bps - 1) // bps) * bps
    f.seek(fat_off)
    fat = f.read(spf * bps)
    nent = len(fat) // 2

    def chain(cl):
        out = []
        while 2 <= cl < 0xFFF8 and cl < nent and len(out) < total:
            out.append(cl)
            cl = struct.unpack_from('<H', fat, cl * 2)[0]
        return out

    def extents(cl, size):
        ext = []
        left = size
        for c in chain(cl):
            if left <= 0:
                break
            off = data_off + (c - 2) * csize
            n = min(csize, left)
            if ext and ext[-1][0] + ext[-1][1] == off:
                ext[-1][1] += n
            else:
                ext.append([off, n])
            left -= n
        return ext

    def read_dir(raw):
        lfn = {}
        for i in range(0, len(raw), 32):
            e = raw[i:i + 32]
            if e[0] == 0:
                break
            if e[0] == 0xE5:
                lfn = {}
                continue
            attr = e[11]
            if attr == 0x0F:
                seq = e[0] & 0x1F
                part = (e[1:11] + e[14:26] + e[28:32]).decode('utf-16le', 'ignore')
                lfn[seq] = part.split('\x00')[0]
                continue
            if attr & 0x08:
                lfn = {}
                continue
            short = e[0:8].decode('latin-1').rstrip()
            ext = e[8:11].decode('latin-1').rstrip()
            name = ''.join(lfn[k] for k in sorted(lfn)) if lfn else (short + ('.' + ext if ext else ''))
            lfn = {}
            if name in ('.', '..'):
                continue
            cl = struct.unpack_from('<H', e, 26)[0]
            size = struct.unpack_from('<I', e, 28)[0]
            yield name.lower(), attr, cl, size

    def dir_bytes(cl):
        b = b''
        for c in chain(cl):
            f.seek(data_off + (c - 2) * csize)
            b += f.read(csize)
        return b

    files = []

    def walk(raw, prefix):
        for name, attr, cl, size in read_dir(raw):
            p = prefix + name
            if attr & 0x10:
                walk(dir_bytes(cl), p + '/')
            else:
                files.append((p, size, extents(cl, size) if size else []))

    f.seek(root_off)
    walk(f.read(nroot * 32), '')
    files.sort()

    def crc(ext):
        c = 0
        for off, n in ext:
            f.seek(off)
            c = zlib.crc32(f.read(n), c)
        return c & 0xFFFFFFFF

    out = sys.stdout
    out.write('/* generated by tools/fwtable.py from %s: %d files */\n' % (path.split('/')[-1], len(files)))
    out.write('static const struct fw_file fw_files_vayu[] = {\n')
    for p, size, ext in files:
        if p.startswith('image/modem.') and size:
            if len(ext) != 1:
                sys.exit('%s is in %d extents' % (p, len(ext)))
            out.write('\t{ "%s", %#x, %#x, %#010x },\n' % (p[6:], ext[0][0], size, crc(ext)))
    out.write('};\n')
    out.write('static const struct fw_extent fw_ext_vayu[] = {\n')
    first = []
    n = 0
    for p, size, ext in files:
        first.append(n)
        for off, ln in ext:
            out.write('\t{ %#x, %#x },\n' % (off, ln))
            n += 1
    out.write('};\n')
    out.write('static const struct fw_entry fw_all_vayu[] = {\n')
    for (p, size, ext), k in zip(files, first):
        out.write('\t{ "%s", %#x, %d, %d },\n' % (p, size, k, len(ext)))
    out.write('};\n')


if __name__ == '__main__':
    main(sys.argv[1])
